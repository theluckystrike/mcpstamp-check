// Prints the README "Scoring" table from the CHECKS export in src/check.mjs.
// Usage: node scripts/scoring-table.mjs          print the table
//        node scripts/scoring-table.mjs --write  replace the table between the README markers
//        node scripts/scoring-table.mjs --check  exit 1 when the README table is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CHECKS } from '../src/check.mjs';

export const START = '<!-- scoring-table:start (generated by scripts/scoring-table.mjs from CHECKS) -->';
export const END = '<!-- scoring-table:end -->';

export function scoringTable(checks = CHECKS) {
  const rows = checks.map((c) =>
    `| \`${c.id}\` | ${c.group} | ${c.title.replace(/\|/g, '\\|')} | ${c.weight} | ${c.blocks.length ? c.blocks.join(', ') : '-'} |`);
  const total = checks.reduce((s, c) => s + c.weight, 0);
  return [
    '| Check | Group | What it tests | Weight | Blocks (fail = not ready) |',
    '|---|---|---|---|---|',
    ...rows,
    `| | | **Total weight (all checks)** | **${total}** | |`,
  ].join('\n');
}

export function replaceTable(readme, table = scoringTable()) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error('README markers not found');
  return readme.slice(0, a + START.length) + '\n' + table + '\n' + readme.slice(b);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = fileURLToPath(new URL('../README.md', import.meta.url));
  const readme = readFileSync(path, 'utf8');
  const next = replaceTable(readme);
  if (process.argv.includes('--write')) {
    writeFileSync(path, next);
  } else if (process.argv.includes('--check')) {
    if (next !== readme) { console.error('README scoring table is out of date: run node scripts/scoring-table.mjs --write'); process.exit(1); }
  } else {
    console.log(scoringTable());
  }
}
